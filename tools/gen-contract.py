def validate(contract: dict[str, Any]) -> None:
    for key in ("contract_version", "ws_hash", "ws", "models_hash", "models"):
        if key not in contract:
            raise ContractError(f"contract/wsContract.json has no {key!r} (contract_version 2 or newer is needed)")
    if contract["contract_version"] not in CONTRACT_VERSIONS:
        raise ContractError(f"contract_version {contract['contract_version']} is not one this generator knows "
                            f"({sorted(CONTRACT_VERSIONS)})")
    # Catches a hand-edited vendored copy.
    for section in ("ws", "models"):
        if canonical_hash(contract[section]) != contract[f"{section}_hash"]:
            raise ContractError(f"contract/wsContract.json does not match its {section}_hash (edited by hand?)")


def outputs(text: str) -> dict[Path, str]:
    contract = json.loads(text)
    validate(contract)
    book = Book(contract)
    files: dict[Path, str] = {SWIFT_DIR / "WsContract.swift": generate_contract_swift(book, text)}
    for label, entries in model_files(book):
        files[SWIFT_DIR / f"WsModel+{label}.swift"] = generate_models_swift(book, label, entries, text)
    segments: dict[str, list[Command]] = {}
    for c in book.commands:
        segments.setdefault(c.name.split(".")[0], []).append(c)
    for segment, commands in segments.items():
        files[SWIFT_DIR / f"Ws+{type_name(segment)}.swift"] = generate_commands_swift(book, segment, commands, text)
    files[SAMPLES_DIR / "ContractSamples.swift"] = generate_samples(book, text)
    files[SAMPLES_DIR / "ModelSamples.swift"] = generate_model_samples(book, text)
    return files


def stale_files(generated: dict[Path, str]) -> list[Path]:
    """Generated files a previous contract produced that this one doesn't."""
    stale = []
    for directory in (SWIFT_DIR, SAMPLES_DIR):
        for path in sorted(directory.glob("*.swift")) if directory.is_dir() else []:
            if path not in generated and path.read_text(encoding="utf-8").startswith(GENERATED_MARK):
                stale.append(path)
    return stale


def check_source(contract: dict[str, Any]) -> None:
    if not SOURCE_JSON.is_file():
        return
    record = json.loads(SOURCE_JSON.read_text(encoding="utf-8"))
    for key in ("ws_hash", "models_hash"):
        if key in record and record[key] != contract[key]:
            raise ContractError(f"contract/SOURCE.json records {key} {record[key][:12]}, the contract has "
                                f"{contract[key][:12]} (vendor with --from)")


def git(server: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(server), *args], check=True, capture_output=True, text=True).stdout.strip()


def vendor(server: Path, note: str | None) -> None:
    source = server / SERVER_CONTRACT
    if not source.is_file():
        raise ContractError(f"{source} not found (is {server} the vaulthalla repository?)")
    text = source.read_text(encoding="utf-8")
    contract = json.loads(text)
    validate(contract)
    shutil.copyfile(source, CONTRACT_JSON)
    version = (server / "VERSION").read_text(encoding="utf-8").strip() if (server / "VERSION").is_file() else None
    commit = git(server, "rev-parse", "--short", "HEAD")
    if git(server, "status", "--porcelain", "--", SERVER_CONTRACT):
        commit += "+uncommitted"
    branch = git(server, "rev-parse", "--abbrev-ref", "HEAD")
    record: dict[str, Any] = {"server_version": version, "server_commit": commit, "server_branch": branch,
                              "source": SERVER_CONTRACT, "contract_version": contract["contract_version"],
                              "ws_hash": contract["ws_hash"], "models_hash": contract["models_hash"]}
    if note:
        record["note"] = note
    SOURCE_JSON.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    print(f"vendored {SERVER_CONTRACT} from {server} (server {version}, {branch} {commit})")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true",
                      help="exit 1 when the contract doesn't match its hashes or the committed Swift drifts from it")
    mode.add_argument("--from", dest="server", metavar="SERVER_REPO",
                      help="copy the server's generated contract into contract/, then regenerate")
    parser.add_argument("--note", help="with --from: a note recorded in contract/SOURCE.json")
    args = parser.parse_args(argv)
    if args.note and not args.server:
        parser.error("--note goes with --from")

    try:
        if args.server:
            vendor(Path(args.server).expanduser().resolve(), args.note)
        text = CONTRACT_JSON.read_text(encoding="utf-8")
        contract = json.loads(text)
        generated = outputs(text)
        if args.check:
            check_source(contract)
    except (ContractError, OSError, subprocess.CalledProcessError, json.JSONDecodeError) as error:
        print(f"gen-contract: {error}", file=sys.stderr)
        return 1

    stale = stale_files(generated)
    if args.check:
        drift = [f"{p.relative_to(ROOT)}: no longer generated (delete it)" for p in stale]
        for path, expected in generated.items():
            committed = path.read_text(encoding="utf-8") if path.exists() else ""
            if committed != expected:
                diff = list(difflib.unified_diff(committed.splitlines(), expected.splitlines(),
                                                 f"{path.relative_to(ROOT)} (committed)",
                                                 f"{path.relative_to(ROOT)} (generated)", lineterm="", n=1))
                changed = sum(1 for d in diff if d[:1] in "+-" and d[:3] not in ("+++", "---"))
                shown = diff[:40] + ([f"... ({len(diff) - 40} more diff lines)"] if len(diff) > 40 else [])
                drift.append(f"{path.relative_to(ROOT)}: {changed} lines differ\n" + "\n".join(shown))
        if drift:
            print("contract drift: the committed Swift is not what contract/wsContract.json generates", file=sys.stderr)
            for d in drift:
                print(d, file=sys.stderr)
            print("fix: python3 tools/gen-contract.py", file=sys.stderr)
            return 1
        print(f"contract: ws_hash and models_hash match contract/wsContract.json; the {len(generated)} generated "
              "files match it")
        return 0

    for path in stale:
        path.unlink()
    for path, content in generated.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"wrote {len(generated)} files under {SWIFT_DIR.relative_to(ROOT)} and {SAMPLES_DIR.relative_to(ROOT)} "
          f"({len(contract['ws'])} commands, {len(contract['models'])} models, ws_hash {contract['ws_hash'][:12]}, "
          f"models_hash {contract['models_hash'][:12]})" + (f"; removed {len(stale)} stale" if stale else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
