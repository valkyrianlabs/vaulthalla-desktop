def source_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def canonical_hash(value: Any) -> str:
    # Same canonical form as the server (core/usage/src/contract/Export.cpp).
    return source_hash(json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False))


def header(contract: dict[str, Any], text: str, what: str) -> list[str]:
    return [
        f"{GENERATED_MARK} from contract/wsContract.json: {what}. Do not edit.",
        "// Refresh from the server with `python3 tools/gen-contract.py --from <server repo>`.",
        f"// contract_version {contract['contract_version']}, ws_hash {contract['ws_hash']}",
        f"// models_hash {contract['models_hash']}",
        f"// source sha256 {source_hash(text)}",
    ]


def swift_text(text: str, indent: int) -> list[str]:
    """A string literal; one too long for a line becomes a multi-line literal with line continuations."""
    pad = " " * indent
    single = pad + swift_string(text)
    if len(single) <= LINE_LIMIT:
        return [single]
    body = text.replace("\\", "\\\\").replace('"""', '\\"""')
    lines: list[str] = []
    line = ""
    for word in body.split(" "):
        # A continued line keeps its separating space at the start of the next line (never trailing whitespace).
        piece = word if not line else " " + word
        if line and len(pad) + len(line) + len(piece) + 2 > LINE_LIMIT:
            lines.append(line + "\\")
            line = " " + word
        else:
            line += piece
    lines.append(line)
    return [pad + '"""'] + [pad + l for l in lines] + [pad + '"""']


def grouped_switch(commands: list[Command], value_of: Callable[[Command], Any],
                   render: Callable[[Any, int], list[str]], indent: int, default: str | None = None) -> list[str]:
    """A switch over WsCommand with one `case` per distinct value (cases listed in contract order). `render` turns a
    value into the lines of its expression at an indent."""
    pad = " " * indent
    groups: dict[str, list[str]] = {}
    order: list[str] = []
    for c in commands:
        v = value_of(c)
        if default is not None and render(v, 0) == [default]:
            continue
        key = json.dumps(v, sort_keys=True)
        if key not in groups:
            groups[key] = []
            order.append(key)
        groups[key].append("." + escaped(c.case))
    out = [f"{pad}switch self {{"]
    for key in order:
        out.extend(wrap_list("case ", groups[key], ":", indent))
        out.extend(render(json.loads(key), indent + 4))
    if default is not None:
        out.append(f"{pad}default: {default}")
    out.append(f"{pad}}}")
    return out


def confirmations_expr(value: list[dict[str, Any]], indent: int) -> list[str]:
    pad = " " * indent
    if not value:
        return [pad + "[]"]
    out = [pad + "["]
    for c in value:
        accept = swift_string(c["accept_field"]) if c.get("accept_field") else "nil"
        out.append(f"{pad}    WsConfirmation(")
        out.append(f"{pad}        code: {swift_string(c['code'])}, acceptField: {accept},")
        summary = swift_text(c.get("description", ""), indent + 12)
        if len(summary) == 1 and len(pad) + 17 + len(summary[0].strip()) <= LINE_LIMIT:
            out.append(f"{pad}        summary: {summary[0].strip()}")
        else:
            out.append(f"{pad}        summary:")
            out.extend(summary)
        out.append(f"{pad}    ),")
    out.append(pad + "]")
    return out


def generate_contract_swift(book: Book, text: str) -> str:
    contract = book.contract
    commands = book.commands
    out = header(contract, text, "the ws command book as Swift")
    out += [
        "",
        "/// The contract this code was generated from. `meta.contract.get` answers the daemon's own `ws_hash` and",
        "/// `models_hash`: when one differs, the daemon was built from another command book (commands may have changed",
        "/// shape) or serializes its models differently.",
        "public enum WsContract {",
        f"    public static let contractVersion = {contract['contract_version']}",
        f"    public static let wsHash = {swift_string(contract['ws_hash'])}",
        f"    public static let modelsHash = {swift_string(contract['models_hash'])}",
        "}",
        "",
        "/// The server models the book names (`User`, `FsEntry`, ...), as the daemon's serializers write them",
        f"/// ({len(book.models)}). Enum-like strings stay `String` with their known values alongside.",
        "public enum WsModel {}",
        "",
        "/// Request types, namespaced like the command names: `auth.user.change_password` is",
        "/// `Ws.Auth.User.ChangePassword`. Each one ties a `WsCommand` to its `Payload` and `Response`.",
        "public enum Ws {}",
        "",
        f"/// Every command the contract types ({len(commands)}). Commands the daemon has but the contract doesn't",
        "/// type yet go through `WsClient.send(command:payload:)`.",
        "public enum WsCommand: String, CaseIterable, Sendable {",
    ]
    for c in commands:
        out.extend(doc_lines(c.raw["description"], 4))
        out.append(f"    case {escaped(c.case)} = {swift_string(c.name)}")

    out += ["", "    /// What the session must be before the router runs the command.",
            "    public var auth: WsAuth {"]
    out += grouped_switch(commands, lambda c: c.raw["auth"], lambda v, i: [" " * i + f".{escaped(v)}"], 8)
    out += ["    }", "",
            "    /// How long a client waits before reporting \"no answer yet\" (never \"failed\": the daemon may",
            "    /// still be working on it).",
            "    public var clientTimeout: Duration {"]
    out += grouped_switch(commands, lambda c: c.raw["client_timeout_ms"],
                          lambda v, i: [" " * i + f".milliseconds({v})"], 8)
    out += ["    }", "",
            "    /// The `OperationSpec` the command runs, when it is one of the daemon's catalogued operations.",
            "    public var operation: String? {"]
    out += grouped_switch(commands, lambda c: c.raw["operation"],
                          lambda v, i: [" " * i + ("nil" if v is None else swift_string(v))], 8, default="nil")
    out += ["    }", "",
            "    /// The refusals the command can answer with: its `refusalKinds` plus its `confirmations` codes.",
            "    public var refusalCodes: [String] {"]
    out += grouped_switch(commands, lambda c: c.raw["refusal_codes"],
                          lambda v, i: wrap_list("[", [swift_string(x) for x in v], "]", i), 8)
    out += ["    }", "",
            "    /// The generic refusal kinds it can answer with: `denied`, `not_found`, `invalid`, `conflict` (ERROR with",
            "    /// that `data.code`), `unauthorized` (the router refused) and `error` (ERROR without a code, by design).",
            "    public var refusalKinds: [String] {"]
    out += grouped_switch(commands, lambda c: c.raw.get("refusal_kinds", []),
                          lambda v, i: wrap_list("[", [swift_string(x) for x in v], "]", i), 8)
    out += ["    }", "",
            "    /// The NeedsConfirmation refusals it can answer with (`WsError.needsConfirmation`) and the payload member",
            "    /// a resend sets to accept each; `confirmation(_:)` looks one up by code.",
            "    public var confirmations: [WsConfirmation] {"]
    out += grouped_switch(commands, lambda c: c.raw.get("confirmations", []), confirmations_expr, 8, default="[]")
    out += ["    }", "",
            "    /// The command book's description.",
            "    public var summary: String {",
            "        switch self {"]
    for c in commands:
        out.append(f"        case .{escaped(c.case)}:")
        out.extend(swift_text(c.raw["description"], 12))
    out += ["        }", "    }", "}"]
    return "\n".join(out) + "\n"


def generate_commands_swift(book: Book, segment: str, commands: list[Command], text: str) -> str:
    command_names = {c.name for c in book.commands}
    out = header(book.contract, text, f"the `{segment}.*` requests")
    out.append("")
    # Namespaces: every dotted prefix that is not itself a command.
    seen: set[str] = set()
    for c in commands:
        parts = c.name.split(".")
        for i in range(1, len(parts)):
            prefix = ".".join(parts[:i])
            if prefix not in command_names and prefix not in seen:
                seen.add(prefix)
                ns = [type_name(p) for p in parts[:i]]
                out.append(f"extension {'.'.join(['Ws'] + ns[:-1])} {{ public enum {ns[-1]} {{}} }}")
    for c in commands:
        out.append("")
        out.append(f"extension {'.'.join(['Ws'] + c.segments[:-1])} {{")
        out.extend(c.forms[0].lines(4))
        out.append("}")
        for form in c.forms[1:]:
            out.append("")
            out.append(f"extension {c.swift_path} {{")
            out.extend(form.lines(4))
            out.append("}")
    return "\n".join(out) + "\n"


def model_files(book: Book) -> list[tuple[str, list[Model]]]:
    """Models grouped by initial, consecutive initials merged until a file is big enough: (A-C, models)."""
    by_initial: dict[str, list[tuple[Model, list[str]]]] = {}
    for m in sorted(book.models.values(), key=lambda m: m.name):
        lines = ["", "extension WsModel {", *m.struct.lines(4), "}"]
        by_initial.setdefault(m.name[0].upper(), []).append((m, lines))
    files: list[tuple[list[str], list[tuple[Model, list[str]]]]] = []
    for initial, entries in by_initial.items():
        size = sum(len(lines) for _, lines in entries)
        if files and sum(len(l) for _, l in files[-1][1]) + size <= MODELS_FILE_LINES:
            files[-1][0].append(initial)
            files[-1][1].extend(entries)
        else:
            files.append(([initial], list(entries)))
    out = []
    for initials, entries in files:
        label = initials[0] if len(initials) == 1 else f"{initials[0]}-{initials[-1]}"
        out.append((label, entries))
    return out


def generate_models_swift(book: Book, label: str, entries: list[tuple[Model, list[str]]], text: str) -> str:
    out = header(book.contract, text, f"the server models {label}")
    for _, lines in entries:
        out.extend(lines)
    return "\n".join(out) + "\n"


