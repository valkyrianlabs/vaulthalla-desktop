class ContractError(Exception):
    pass


# ---- names -----------------------------------------------------------------------------------------------------

def words(name: str) -> list[str]:
    """snake_case and dotted names split into words; camelCase segments stay one word ("isAuthenticated")."""
    return [w for w in re.split(r"[._\-]", name) if w]


def upper_first(word: str) -> str:
    return word[:1].upper() + word[1:]


def lower_first(word: str) -> str:
    return word[:1].lower() + word[1:]


def type_name(name: str) -> str:
    out = "".join(ACRONYMS.get(w, upper_first(w)) for w in words(name))
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", out):
        raise ContractError(f"{name!r} does not make a Swift type name")
    return out


def member_name(name: str) -> str:
    ws = words(name)
    if not ws:
        raise ContractError(f"empty name {name!r}")
    out = ws[0] + "".join(ACRONYMS.get(w, upper_first(w)) for w in ws[1:])
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", out):
        raise ContractError(f"{name!r} does not make a Swift identifier")
    return out


def value_name(value: str) -> str:
    """A Swift case or constant for an enum string: "email_validated" -> emailValidated, "Backblaze B2" ->
    backblazeB2, "AWS" -> aws, "model:glb" -> modelGlb."""
    ws = [w for w in re.split(r"[^A-Za-z0-9]+", value) if w]
    if not ws:
        raise ContractError(f"enum value {value!r} does not make a Swift identifier")
    first = ws[0].lower() if ws[0].isupper() else lower_first(ws[0])
    out = first + "".join(ACRONYMS.get(w, upper_first(w)) for w in ws[1:])
    return "_" + out if out[0].isdigit() else out


def escaped(identifier: str) -> str:
    return f"`{identifier}`" if identifier in SWIFT_KEYWORDS else identifier


def safe_type(base: str) -> str:
    return base + "Value" if base in RESERVED_TYPES else base


def singular(base: str) -> str:
    # The element of `recipient_role_assignments` is a `RecipientRoleAssignment`.
    return base[:-1] if base.endswith("s") and not base.endswith("ss") else base + "Item"


def swift_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def doc_lines(text: str, indent: int) -> list[str]:
    pad = " " * indent + "/// "
    out: list[str] = []
    line = ""
    for word in text.split():
        if line and len(pad) + len(line) + 1 + len(word) > LINE_LIMIT:
            out.append(pad + line)
            line = word
        else:
            line = f"{line} {word}".strip()
    if line:
        out.append(pad + line)
    return out


def wrap_list(prefix: str, items: list[str], suffix: str, indent: int, separator: str = ", ") -> list[str]:
    """`prefix a, b, c suffix`, continued on further lines indented under the prefix when too long."""
    pad = " " * indent
    one = pad + prefix + separator.join(items) + suffix
    if len(one) <= LINE_LIMIT:
        return [one]
    lines: list[str] = []
    line = pad + prefix
    cont = " " * (indent + len(prefix))
    for i, item in enumerate(items):
        piece = item + (separator.rstrip() if i < len(items) - 1 else suffix)
        candidate = (line + piece) if line.endswith(prefix) else (line + " " + piece)
        if len(candidate) > LINE_LIMIT and line.strip() != prefix.strip():
            lines.append(line)
            line = cont + piece
        else:
            line = candidate
    lines.append(line)
    return lines


class Lines(list):
    """Code lines; one too long is broken after its first `(` with the arguments on a continuation line."""

    def append(self, line: str) -> None:
        if len(line) > LINE_LIMIT and "(" in line:
            head, args = line.split("(", 1)
            continuation = " " * (len(line) - len(line.lstrip()) + 4)
            super().append(head + "(")
            super().append(continuation + args)
        else:
            super().append(line)


# ---- type model ------------------------------------------------------------------------------------------------

# Shapes a `partial` member patches (a model name or a nested Struct), collected while the book is resolved; their
# Patch types (and those of the shapes nested in them) are generated after.
PATCH_ROOTS: list["str | Struct"] = []


class Ref:
    """A resolved Swift type. `patchable` is the shape behind it when it is one object (a model name or a nested
    Struct): a Patch of the owner patches that member with the shape's own Patch."""

    def __init__(self, swift: str, patchable: "str | Struct | None" = None):
        self.swift = swift
        self.patchable = patchable


def model_type(name: str) -> str:
    return f"WsModel.{name}"


def patch_type(target: "str | Struct") -> str:
    return (model_type(target) if isinstance(target, str) else target.name) + ".Patch"


def concrete_types(spec: dict[str, Any], path: str) -> list[str]:
    concrete = [t for t in spec.get("types", []) if t != "null"]
    if not concrete:
        raise ContractError(f"{path}: no types")
    return concrete


def resolve(spec: dict[str, Any], scope: "Scope", hint: str, payload: bool, notes: list[str], path: str) -> Ref:
    """The Swift type of one contract shape (a field, a union alternative, an array element or a map value), with
    the types it needs nested in `scope`. Null is the caller's business."""
    concrete = concrete_types(spec, path)
    if spec.get("one_of"):
        return Ref(scope.add(Union(safe_type(hint), spec["one_of"], payload, path)).name)
    if len(concrete) > 1:
        notes.append(union_note(spec, concrete))
        return Ref("JSONValue")
    kind = concrete[0]
    if kind == "string":
        if spec.get("enum"):
            return Ref(string_enum(spec["enum"], scope, hint, payload, notes, element=False))
        return Ref("String")
    if kind == "integer":
        return Ref("Int64")
    if kind == "number":
        return Ref("Double")
    if kind == "boolean":
        return Ref("Bool")
    if kind == "object":
        return resolve_object(spec, scope, hint, payload, notes, path, element=False)
    if kind == "array":
        element = spec.get("element")
        if element:
            inner = resolve(element, scope, singular(hint), payload, notes, path + "[]")
            return Ref("[" + inner.swift + ("?" if "null" in element["types"] else "") + "]")
        items = spec.get("items", "")
        if items == "string":
            if spec.get("item_enum"):
                return Ref(f"[{string_enum(spec['item_enum'], scope, singular(hint), payload, notes, element=True)}]")
            return Ref("[String]")
        if items == "integer":
            return Ref("[Int64]")
        if items == "number":
            return Ref("[Double]")
        if items == "boolean":
            return Ref("[Bool]")
        if items == "object":
            return Ref("[" + resolve_object(spec, scope, singular(hint), payload, notes, path + "[]",
                                            element=True).swift + "]")
        notes.append("The contract does not type the elements.")
        return Ref("JSONValue")
    raise ContractError(f"{path}: unknown JSON type {kind!r}")


def resolve_object(spec: dict[str, Any], scope: "Scope", hint: str, payload: bool, notes: list[str], path: str,
                   element: bool) -> Ref:
    if spec.get("partial") and not element:
        if spec.get("model"):
            PATCH_ROOTS.append(spec["model"])
            return Ref(patch_type(spec["model"]))
        if spec.get("fields"):
            nested = scope.add(Struct(safe_type(hint), spec["fields"], payload, path))
            PATCH_ROOTS.append(nested)
            return Ref(patch_type(nested))
    if spec.get("model"):
        return Ref(model_type(spec["model"]), spec["model"])
    if spec.get("fields"):
        nested = scope.add(Struct(safe_type(hint), spec["fields"], payload, path))
        return Ref(nested.name, nested)
    if spec.get("values") and not element:
        values = spec["values"]
        value_hint = type_name(values["name"]) if values.get("name") else hint + "Value"
        inner = resolve(values, scope, value_hint, payload, notes, path + "{}")
        return Ref("[String: " + inner.swift + ("?" if "null" in values["types"] else "") + "]")
    what = "Elements are objects" if element else "An object"
    notes.append(f"{what} the contract leaves open (no fields, model or value shape), kept as JSONObject.")
    return Ref("JSONObject")


def string_enum(values: list[str], scope: "Scope", hint: str, payload: bool, notes: list[str], element: bool) -> str:
    if payload:
        return scope.add(SwiftEnum(safe_type(hint), values)).name
    known = scope.add(KnownValues(safe_type(hint), values))
    notes.append(f"{'Each one of' if element else 'One of'} the known values in `{known.name}`; a newer daemon may "
                 "send others.")
    return "String"


def union_note(spec: dict[str, Any], concrete: list[str]) -> str:
    parts = []
    for t in concrete:
        if t == "array" and spec.get("items"):
            items = spec["items"]
            if spec.get("item_enum"):
                items += " (" + ", ".join(spec["item_enum"]) + ")"
            parts.append(f"array of {items}")
        else:
            parts.append(t)
    return "JSON: " + " | ".join(parts) + "."


class Scope:
    """A generated Swift type that nests others."""

    def __init__(self, name: str, path: str):
        self.name = name
        self.path = path
        self.nested: list[Any] = []

    def add(self, t: Any) -> Any:
        if any(n.name == t.name for n in self.nested):
            raise ContractError(f"{self.path}: nested types collide in Swift: {t.name}")
        self.nested.append(t)
        return t

    def nested_lines(self, indent: int) -> list[str]:
        out: list[str] = []
        for t in self.nested:
            out.append("")
            out.extend(t.lines(indent))
        return out


class Field:
    """One contract member resolved to Swift: its type, its optionality and how it is coded."""

    def __init__(self, raw: dict[str, Any], owner: "Struct", payload: bool):
        self.raw = raw
        self.json_name: str = raw["name"]
        self.swift_name = member_name(self.json_name)
        self.required: bool = raw["required"]
        self.nullable = "null" in raw["types"]
        self.notes: list[str] = []
        ref = resolve(raw, owner, type_name(self.json_name), payload, self.notes, f"{owner.path}.{self.json_name}")
        self.base = ref.swift
        self.patchable = ref.patchable
        if self.base == "JSONValue":
            # JSONValue carries null itself, so a nullable union needs no extra wrapper.
            self.kind = "required" if self.required else "optional_json"
        elif self.required:
            self.kind = "required_nullable" if self.nullable else "required"
        else:
            self.kind = "optional_nullable" if self.nullable else "optional"

    @property
    def doc(self) -> str:
        text = self.raw.get("description", "").strip()
        extra = list(self.notes)
        if "minimum" in self.raw:
            extra.append(f"Minimum {self.raw['minimum']}.")
        if "maximum" in self.raw:
            extra.append(f"Maximum {self.raw['maximum']}.")
        extra.extend(kind_note(self.kind))
        return " ".join(([text] if text else []) + extra)


def kind_note(kind: str) -> list[str]:
    if kind == "required_nullable":
        return ["Always sent; nil is null."]
    if kind == "optional_nullable":
        return ["nil omits it, `.null` sends null."]
    if kind == "optional_json":
        return ["nil omits it."]
    return []


class PatchField:
    """A member of a Patch: the owner's member, optional, with a nested shape replaced by that shape's Patch."""

    def __init__(self, field: Field):
        self.json_name = field.json_name
        self.swift_name = field.swift_name
        self.base = patch_type(field.patchable) if field.patchable is not None else field.base
        if self.base == "JSONValue":
            self.kind = "optional_json"
        else:
            self.kind = "optional_nullable" if field.nullable else "optional"
        text = field.raw.get("description", "").strip()
        self.doc = " ".join(([text] if text else []) + field.notes + ["nil leaves it unchanged."]
                            + (["`.null` clears it."] if self.kind == "optional_nullable" else []))


class SwiftEnum:
    """A closed String enum: a payload member the daemon only accepts these values for."""

    def __init__(self, name: str, values: list[str]):
        self.name = name
        self.values = values
        self.cases = [value_name(v) for v in values]
        if len(set(self.cases)) != len(self.cases):
            raise ContractError(f"enum {name}: values collide as Swift cases: {values}")

    def lines(self, indent: int) -> list[str]:
        pad = " " * indent
        out = [f"{pad}public enum {self.name}: String, Codable, Hashable, Sendable, CaseIterable {{"]
        for case, value in zip(self.cases, self.values):
            raw = "" if case == value else f" = {swift_string(value)}"
            out.append(f"{pad}    case {escaped(case)}{raw}")
        out.append(f"{pad}}}")
        return out


class KnownValues:
    """The values the contract lists for a String member it keeps open: `static let` constants, never a closed
    enum (a newer daemon may answer with a value this build doesn't know)."""

    def __init__(self, name: str, values: list[str]):
        self.name = name
        self.values = values
        self.members = [value_name(v) for v in values]
        if len(set(self.members)) != len(self.members) or "allValues" in self.members:
            raise ContractError(f"known values {name}: values collide as Swift names: {values}")

    def lines(self, indent: int) -> list[str]:
        pad = " " * indent
        out = [f"{pad}/// Known values (the member stays a String: a newer daemon may send others).",
               f"{pad}public enum {self.name} {{"]
        for member, value in zip(self.members, self.values):
            out.append(f"{pad}    public static let {escaped(member)} = {swift_string(value)}")
        out.extend(wrap_list("public static let allValues: [String] = [", [escaped(m) for m in self.members], "]",
                             indent + 4))
        out.append(f"{pad}}}")
        return out


class Union(Scope):
    """A `one_of` member: an enum with one case per alternative, decoded by trying them in the contract's order."""

    def __init__(self, name: str, alternatives: list[dict[str, Any]], payload: bool, path: str):
        super().__init__(name, path)
        kinds = [concrete_types(a, f"{path}|{i}")[0] for i, a in enumerate(alternatives)]
        for i, a in enumerate(alternatives):
            if len(concrete_types(a, f"{path}|{i}")) != 1:
                raise ContractError(f"{path}: union alternative {i} has several types")
        self.cases: list[tuple[str, str, str]] = []  # (case, Swift type, doc)
        for i, alt in enumerate(alternatives):
            kind = kinds[i]
            case, hint = KIND_CASES[kind], upper_first(KIND_CASES[kind])
            if kinds.count(kind) > 1:
                case, hint = self.disambiguated(alt, kind, i)
            if kind == "array":
                hint = singular(name)
            if hint == name:
                hint += "Value"
            notes: list[str] = []
            ref = resolve(alt, self, hint, payload, notes, f"{path}|{case}")
            doc = " ".join(([alt["description"].strip()] if alt.get("description") else []) + notes)
            self.cases.append((case, ref.swift, doc))
        names = [c[0] for c in self.cases]
        if len(set(names)) != len(names):
            raise ContractError(f"{path}: union alternatives collide as Swift cases: {names}")

    @staticmethod
    def disambiguated(alt: dict[str, Any], kind: str, index: int) -> tuple[str, str]:
        """A case name (and a name for a nested type it needs) when several alternatives share a JSON type: after
        the model, or the first member of an inline object ({vault_id} -> vaultID(VaultIDObject))."""
        if alt.get("model"):
            return lower_first(alt["model"]) + ("s" if kind == "array" else ""), alt["model"]
        if kind == "object" and alt.get("fields"):
            first = alt["fields"][0]["name"]
            return member_name(first), type_name(first) + "Object"
        return KIND_CASES[kind] + str(index + 1), upper_first(KIND_CASES[kind]) + str(index + 1)

    def lines(self, indent: int) -> list[str]:
        pad = " " * indent
        inner = " " * (indent + 4)
        body = " " * (indent + 8)
        tried = ", ".join(c[0] for c in self.cases)
        out = Lines(doc_lines(f"One of these, tried in this order when decoding: {tried}.", indent))
        out.append(f"{pad}public enum {self.name}: Codable, Hashable, Sendable {{")
        for case, swift, doc in self.cases:
            if doc:
                out.extend(doc_lines(doc, indent + 4))
            out.append(f"{inner}case {escaped(case)}({swift})")
        out += ["", f"{inner}public init(from decoder: any Decoder) throws {{",
                f"{body}let container = try decoder.singleValueContainer()"]
        for i, (case, swift, _) in enumerate(self.cases):
            keyword = "if" if i == 0 else "} else if"
            out.append(f"{body}{keyword} let value = try? container.decode({swift}.self) {{")
            out.append(f"{body}    self = .{escaped(case)}(value)")
        out.append(f"{body}}} else {{")
        out.append(f"{body}    throw DecodingError.dataCorruptedError(")
        out.append(f"{body}        in: container,")
        out.append(f"{body}        debugDescription: {swift_string(f'{self.name}: none of {tried} matches')}")
        out.append(f"{body}    )")
        out.append(f"{body}}}")
        out.append(f"{inner}}}")
        out += ["", f"{inner}public func encode(to encoder: any Encoder) throws {{",
                f"{body}var container = encoder.singleValueContainer()", f"{body}switch self {{"]
        for case, _, _ in self.cases:
            out.append(f"{body}case .{escaped(case)}(let value): try container.encode(value)")
        out += [f"{body}}}", f"{inner}}}"]
        out.extend(self.nested_lines(indent + 4))
        out.append(f"{pad}}}")
        return list(out)


class Struct(Scope):
    def __init__(self, name: str, fields: list[dict[str, Any]], payload: bool, path: str, doc: str = ""):
        super().__init__(name, path)
        self.doc = doc
        self.needs_patch = False
        self.fields = [Field(f, self, payload) for f in fields]
        names = [f.swift_name for f in self.fields]
        if len(set(names)) != len(names):
            raise ContractError(f"{path}: members collide in Swift: {names}")

    def fields_raw(self) -> list[dict[str, Any]]:
        return [f.raw for f in self.fields]

    def lines(self, indent: int) -> list[str]:
        out = doc_lines(self.doc, indent) if self.doc else []
        nested = self.nested_lines(indent + 4)
        if self.needs_patch:
            nested += ["", *doc_lines(f"A merge patch of `{self.name}`: only the members set are sent.", indent + 4)]
            nested += struct_lines("Patch", [PatchField(f) for f in self.fields], indent + 4, [])
        return out + struct_lines(self.name, self.fields, indent, nested)


def struct_lines(name: str, members: list[Any], indent: int, nested: list[str]) -> list[str]:
    """A Codable struct: members (Field or PatchField: json_name, swift_name, base, kind, doc), memberwise init,
    coding keys, and explicit coding when a member must tell absent from null."""
    pad = " " * indent
    inner = " " * (indent + 4)
    out = [f"{pad}public struct {name}: Codable, Hashable, Sendable {{"]
    for f in members:
        if f.doc:
            out.extend(doc_lines(f.doc, indent + 4))
        out.append(f"{inner}public var {escaped(f.swift_name)}: {swift_type(f)}")
    if members:
        out.append("")

    params = [f"{f.swift_name}: {swift_type(f)}" + ("" if f.kind == "required" else " = nil") for f in members]
    out.extend(wrap_list("public init(", params, ") {", indent + 4))
    for f in members:
        out.append(f"{inner}    self.{f.swift_name} = {escaped(f.swift_name)}")
    out.append(f"{inner}}}")

    if members:
        out.append("")
        out.append(f"{inner}enum CodingKeys: String, CodingKey {{")
        for f in members:
            raw = "" if f.swift_name == f.json_name else f" = {swift_string(f.json_name)}"
            out.append(f"{inner}    case {escaped(f.swift_name)}{raw}")
        out.append(f"{inner}}}")

    # Synthesized Codable decodes and encodes T and T? correctly; nullable members need to tell absent from null.
    if any(f.kind in ("required_nullable", "optional_nullable", "optional_json") for f in members):
        out.extend(coding_lines(members, indent + 4))
    out.extend(nested)
    out.append(f"{pad}}}")
    return out


def swift_type(f: Any) -> str:
    if f.kind == "required":
        return f.base
    if f.kind == "optional_nullable":
        return f"Nullable<{f.base}>?"
    return f.base + "?"


def coding_lines(members: list[Any], indent: int) -> list[str]:
    pad = " " * indent
    body = " " * (indent + 4)
    out = Lines()
    out += ["", f"{pad}public init(from decoder: any Decoder) throws {{",
            f"{body}let container = try decoder.container(keyedBy: CodingKeys.self)"]
    for f in members:
        key = f".{escaped(f.swift_name)}"
        target = f"self.{f.swift_name}"
        if f.kind == "required":
            out.append(f"{body}{target} = try container.decode({f.base}.self, forKey: {key})")
        elif f.kind == "required_nullable":
            out.append(f"{body}{target} = try container.decode({f.base}?.self, forKey: {key})")
        elif f.kind == "optional":
            out.append(f"{body}{target} = try container.decodeIfPresent({f.base}.self, forKey: {key})")
        else:
            wrapped = f"Nullable<{f.base}>" if f.kind == "optional_nullable" else f.base
            out.append(f"{body}{target} = container.contains({key})")
            out.append(f"{body}    ? try container.decode({wrapped}.self, forKey: {key}) : nil")
    out.append(f"{pad}}}")
    out.append("")
    out.append(f"{pad}public func encode(to encoder: any Encoder) throws {{")
    out.append(f"{body}var container = encoder.container(keyedBy: CodingKeys.self)")
    for f in members:
        key = f".{escaped(f.swift_name)}"
        method = "encode" if f.kind in ("required", "required_nullable") else "encodeIfPresent"
        out.append(f"{body}try container.{method}(self.{f.swift_name}, forKey: {key})")
    out.append(f"{pad}}}")
    return list(out)


# ---- the book --------------------------------------------------------------------------------------------------

class Model:
    def __init__(self, raw: dict[str, Any]):
        self.raw = raw
        self.name: str = raw["name"]
        if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", self.name) or self.name in RESERVED_TYPES:
            raise ContractError(f"model {self.name!r} does not make a Swift type name (or would shadow one)")
        self.struct = Struct(self.name, raw["fields"], False, f"model {self.name}", raw.get("description", ""))


class Command:
    def __init__(self, raw: dict[str, Any], models: dict[str, Model]):
        self.raw = raw
        self.name: str = raw["command"]
        self.segments = [type_name(s) for s in self.name.split(".")]
        for s in self.segments:
            if s in RESERVED_TYPES:
                raise ContractError(f"{self.name}: segment {s} would shadow a type the generated code uses")
        self.case = member_name(self.name.replace(".", "_"))
        self.swift_path = "Ws." + ".".join(self.segments)
        if raw["auth"] not in AUTH_LEVELS:
            raise ContractError(f"{self.name}: unknown auth level {raw['auth']!r}")
        if raw["input"] not in INPUTS:
            raise ContractError(f"{self.name}: unknown input {raw['input']!r}")
        for c in raw.get("confirmations", []):
            if not c.get("code"):
                raise ContractError(f"{self.name}: a confirmation without a code")
        response_model = raw.get("response_model")
        if response_model:
            if response_model not in models:
                raise ContractError(f"{self.name}: response_model {response_model!r} is not a declared model")
            if raw["response"] != models[response_model].raw["fields"]:
                raise ContractError(f"{self.name}: response does not list {response_model}'s fields")
        self.forms = [Form(self, None, raw["payload"], raw["response"], raw["description"], response_model)]
        for v in raw["variants"]:
            if v.get("mode") != "share":
                raise ContractError(f"{self.name}: unknown variant mode {v.get('mode')!r}")
            self.forms.append(Form(self, "ShareMode", v["payload"], v["response"], v.get("description", ""), None))


class Form:
    """A request type: the command's own shape, or a session-mode variant nested in it."""

    def __init__(self, command: Command, variant: str | None, payload: list[dict[str, Any]],
                 response: list[dict[str, Any]], description: str, response_model: str | None):
        self.command = command
        self.variant = variant
        self.description = description
        self.swift_path = command.swift_path + (f".{variant}" if variant else "")
        self.payload_input = command.raw["input"] == "payload"
        self.payload = Struct("Payload", payload, True, f"{command.name} payload") \
            if self.payload_input and payload else None
        self.response_model = response_model
        self.response_raw = response
        self.response = Struct("Response", response, False, f"{command.name} response") \
            if response and not response_model else None
        if not self.payload_input and payload:
            raise ContractError(f"{command.name}: input {command.raw['input']!r} but payload fields are listed")

    def structs(self) -> list[Struct]:
        return [s for s in (self.payload, self.response) if s is not None]

    def lines(self, indent: int) -> list[str]:
        pad = " " * indent
        inner = " " * (indent + 4)
        name = self.variant or self.command.segments[-1]
        out = doc_lines(self.description, indent) if self.description else []
        out.append(f"{pad}public enum {name}: WsRequest {{")
        out.append(f"{inner}public static let command = WsCommand.{escaped(self.command.case)}")
        if self.payload:
            out.append("")
            out.extend(self.payload.lines(indent + 4))
        elif self.payload_input:
            out.append(f"{inner}public typealias Payload = WsEmpty")
        else:
            reads = "nothing" if self.command.raw["input"] == "none" else "the envelope token"
            out.append(f"{inner}/// The daemon reads {reads}; the payload is sent as null.")
            out.append(f"{inner}public typealias Payload = WsNoPayload")
        if self.response_model:
            if self.payload:
                out.append("")
            out.append(f"{inner}/// The answer is the `{self.response_model}` model as a whole.")
            out.append(f"{inner}public typealias Response = {model_type(self.response_model)}")
        elif self.response:
            out.append("")
            out.extend(self.response.lines(indent + 4))
        else:
            if self.payload:
                out.append("")
            out.append(f"{inner}public typealias Response = WsEmpty")
        out.append(f"{pad}}}")
        return out


class Book:
    """The resolved contract: models, commands and which shapes need a Patch."""

    def __init__(self, contract: dict[str, Any]):
        PATCH_ROOTS.clear()
        self.contract = contract
        self.models: dict[str, Model] = {}
        for raw in contract["models"]:
            if raw["name"] in self.models:
                raise ContractError(f"model {raw['name']} is declared twice")
            self.models[raw["name"]] = Model(raw)
        self.commands = [Command(c, self.models) for c in contract["ws"]]
        names = [c.case for c in self.commands]
        if len(set(names)) != len(names):
            raise ContractError("command names collide as Swift cases")
        self.check_model_refs()
        self.mark_patches()

    def check_model_refs(self) -> None:
        def walk(spec: dict[str, Any], where: str) -> None:
            if spec.get("model") and spec["model"] not in self.models:
                raise ContractError(f"{where}: names model {spec['model']!r}, which the contract doesn't declare")
            for f in spec.get("fields", []) + spec.get("one_of", []):
                walk(f, where)
            for key in ("values", "element"):
                if spec.get(key):
                    walk(spec[key], where)

        for m in self.models.values():
            for f in m.raw["fields"]:
                walk(f, f"model {m.name}")
        for c in self.commands:
            for f in c.raw["payload"] + c.raw["response"]:
                walk(f, c.name)
            for v in c.raw["variants"]:
                for f in v["payload"] + v["response"]:
                    walk(f, c.name)

    def mark_patches(self) -> None:
        work = [self.models[t].struct if isinstance(t, str) else t for t in PATCH_ROOTS]
        while work:
            s = work.pop()
            if s.needs_patch:
                continue
            s.needs_patch = True
            for f in s.fields:
                if f.patchable is not None:
                    work.append(self.models[f.patchable].struct if isinstance(f.patchable, str) else f.patchable)

    def patched_models(self) -> list[Model]:
        return [m for m in self.models.values() if m.struct.needs_patch]


