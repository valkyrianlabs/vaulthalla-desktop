#!/usr/bin/env python3
"""Turn the daemon's ws contract (contract/wsContract.json) into Swift for VHContract.

The contract is the server's ws command book and the models it names (core/usage, published by `vh_usage --json`),
vendored here from `web/src/util/generated/wsContract.json` in the server repository. This tool writes

  Sources/VHContract/Generated/WsContract.swift         WsContract (hashes), WsCommand and its metadata, `Ws`, `WsModel`
  Sources/VHContract/Generated/WsModel+<A-C>.swift      the server models, `WsModel.<Name>` (split by initial)
  Sources/VHContract/Generated/Ws+<Segment>.swift       one WsRequest type per command, by first name segment
  Tests/VHContractTests/Generated/ContractSamples.swift a minimal and a full JSON sample per payload and response
  Tests/VHContractTests/Generated/ModelSamples.swift    a minimal and a full JSON sample per model and patch

  gen-contract.py                     regenerate everything from contract/wsContract.json
  gen-contract.py --check             exit 1 when the vendored contract doesn't match its hashes or the committed Swift
                                      is not what it generates
  gen-contract.py --from ../vaulthalla [--note TEXT]
                                      vendor the server's contract (recording its version, commit, branch and hashes in
                                      contract/SOURCE.json), then regenerate

Type mapping, kept faithful rather than clever (the web's generated TypeScript is the reference):
  string -> String; integer -> Int64; number -> Double; boolean -> Bool.
  A string with `enum`: in a command payload a nested String enum; anywhere else it stays String (a newer daemon may
  add values) and a nested namespace of `static let` known values is generated.
  object: naming a `model` -> WsModel.<Name>; with `fields` -> a nested struct; with `values` -> [String: T];
  `partial` -> <Shape>.Patch (a merge patch: every member optional, nested shapes patched too, nullable members as
  Nullable<T>? so "leave alone" and "clear" differ); with no shape at all -> JSONObject (the doc says so).
  array: `element`, else `items` (+ `item_enum`, `model`, `fields`) -> [T].
  `one_of` -> a nested enum with associated values, decoded by trying the alternatives in the contract's order (the
  contract has no discriminator). Several types without `one_of` -> JSONValue.
  required -> T; required and nullable -> T? (the key is always sent); optional -> T? (the key is omitted when nil);
  optional and nullable -> Nullable<T>? (nil omits the key, .null sends null: "clear" and "leave alone" differ).
  A command whose `response_model` names a model answers with that model as a whole: Response = WsModel.<Name>.
Standard library only.
"""

