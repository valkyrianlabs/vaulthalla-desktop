def int_sample(spec: dict[str, Any]) -> int:
    value = spec.get("minimum", 0) + 1
    return min(value, spec["maximum"]) if "maximum" in spec else value


def sample_field(raw: dict[str, Any], full: bool, models: dict[str, Model]) -> Any:
    if not full and raw.get("required", True) and "null" in raw["types"]:
        return None
    return sample_shape(raw, full, models)


def sample_shape(spec: dict[str, Any], full: bool, models: dict[str, Model]) -> Any:
    if spec.get("one_of"):
        # The first alternative: decoding tries them in order, so the sample round-trips as itself.
        return sample_shape(spec["one_of"][0], full, models)
    t = [t for t in spec["types"] if t != "null"][0]
    if t == "string":
        return (spec.get("enum") or ["x"])[0]
    if t == "integer":
        return int_sample(spec)
    if t == "number":
        return 1.5
    if t == "boolean":
        return True
    if t == "object":
        if spec.get("model"):
            return sample_object(models[spec["model"]].raw["fields"], full, models)
        if spec.get("fields"):
            return sample_object(spec["fields"], full, models)
        if spec.get("values"):
            return {"k": sample_shape(spec["values"], full, models)} if full else {}
        return {"k": "v"} if full else {}
    if t == "array":
        if not full:
            return []
        if spec.get("element"):
            return [sample_shape(spec["element"], full, models)]
        items = spec.get("items", "")
        if items == "string":
            return [(spec.get("item_enum") or ["x"])[0]]
        if items == "integer":
            return [int_sample(spec)]
        if items == "number":
            return [1.5]
        if items == "boolean":
            return [True]
        if items == "object":
            if spec.get("model"):
                return [sample_object(models[spec["model"]].raw["fields"], full, models)]
            return [sample_object(spec["fields"], full, models) if spec.get("fields") else {"k": "v"}]
        return ["x"]
    raise ContractError(f"no sample for type {t!r}")


def sample_object(fields: list[dict[str, Any]], full: bool, models: dict[str, Model]) -> dict[str, Any]:
    return {f["name"]: sample_field(f, full, models) for f in fields if full or f["required"]}


def sample_literal(value: Any, indent: int) -> list[str]:
    """A raw string literal holding `value` as JSON: compact when it fits, else pretty-printed over several lines."""
    pad = " " * indent
    compact = json.dumps(value, separators=(",", ":"), sort_keys=True, ensure_ascii=False)
    if len(pad) + len(compact) + 5 <= LINE_LIMIT:
        return [f'{pad}#"{compact}"#,']
    pretty = json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False).splitlines()
    return [f'{pad}#"""'] + [pad + line for line in pretty] + [f'{pad}"""#,']


